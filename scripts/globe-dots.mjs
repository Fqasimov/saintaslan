// Samples the land masses into an even field of dots for the globe in the stock
// section, so the site ships ~20 KB of points instead of a map and a geo library's
// point-in-polygon work at runtime.  Run: node scripts/globe-dots.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { geoContains } from 'd3-geo'
import { feature } from 'topojson-client'

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-110m.json', import.meta.url)))
const land = feature(topo, topo.objects.land)

const STEP = 1.6 // degrees of latitude between rows
const out = []
for (let lat = -58; lat <= 78; lat += STEP) {
  // Fewer dots per row towards the poles, so the spacing stays even on the sphere.
  const n = Math.max(1, Math.round((360 / STEP) * Math.cos((lat * Math.PI) / 180)))
  for (let i = 0; i < n; i++) {
    const lon = -180 + (i * 360) / n
    if (geoContains(land, [lon, lat])) out.push(Math.round(lon * 10), Math.round(lat * 10))
  }
}
writeFileSync(
  new URL('../src/data/globe-dots.ts', import.meta.url),
  `// Generated by scripts/globe-dots.mjs: [lon*10, lat*10, ...] for every land dot.\nexport const LAND_DOTS = new Int16Array([${out.join(',')}])\n`,
)
console.log(out.length / 2, 'dots')
