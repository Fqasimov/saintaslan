"""
Traces the house's logo (assets-src/logo.jpg: black "SAINT ASLAN" on a red disc) into
vector paths, one per letter, so the name can be drawn crisp at any size and its
letters animated one by one. Writes src/brand/logo-paths.ts.

Run: python3 scripts/trace-logo.py   (needs Pillow, numpy, opencv-python-headless)
"""

from pathlib import Path

import cv2
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets-src" / "logo.jpg"
OUT = ROOT / "src" / "brand" / "logo-paths.ts"

BOX = (92, 352, 718, 416)  # the name, with a margin
UP = 10  # trace at 10x so the curves of the S come out smooth


def main():
    rgb = Image.open(SRC).convert("RGB").crop(BOX)
    disc = np.asarray(Image.open(SRC).convert("RGB"))[200, 400]
    w, h = rgb.size
    big = np.asarray(rgb.resize((w * UP, h * UP), Image.BICUBIC)).astype(np.float32)
    # Distance from the disc red, so anti-aliased edges sit at the true middle.
    ink = np.linalg.norm(big - disc.astype(np.float32), axis=2)
    ink = cv2.GaussianBlur(ink, (0, 0), UP * 0.42)
    mask = (ink > np.linalg.norm(disc.astype(np.float32)) * 0.5).astype(np.uint8) * 255

    contours, hierarchy = cv2.findContours(mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    hierarchy = hierarchy[0]

    def to_path(c):
        c = cv2.approxPolyDP(c, UP * 0.42, True)[:, 0, :].astype(float) / UP
        n = len(c)
        d = [f"M{c[0][0]:.2f} {c[0][1]:.2f}"]
        for i in range(n):
            p0, p1, p2, p3 = c[(i - 1) % n], c[i], c[(i + 1) % n], c[(i + 2) % n]
            seg = np.linalg.norm(p2 - p1)
            # Long straight runs stay straight; short ones are smoothed (the curves of S).
            if seg > 2.4:
                d.append(f"L{p2[0]:.2f} {p2[1]:.2f}")
            else:
                c1 = p1 + (p2 - p0) / 6
                c2 = p2 - (p3 - p1) / 6
                d.append(f"C{c1[0]:.2f} {c1[1]:.2f} {c2[0]:.2f} {c2[1]:.2f} {p2[0]:.2f} {p2[1]:.2f}")
        return "".join(d) + "Z"

    glyphs = []
    for i, c in enumerate(contours):
        if hierarchy[i][3] != -1 or cv2.contourArea(c) < (UP * UP * 6):
            continue
        parts = [to_path(c)]
        child = hierarchy[i][2]
        while child != -1:
            if cv2.contourArea(contours[child]) > UP * UP * 2:
                parts.append(to_path(contours[child]))
            child = hierarchy[child][0]
        x = cv2.boundingRect(c)[0] / UP
        glyphs.append((x, "".join(parts)))
    glyphs.sort()

    # Tight viewBox around the letters.
    ys, xs = np.nonzero(mask)
    x0, y0 = xs.min() / UP, ys.min() / UP
    x1, y1 = xs.max() / UP, ys.max() / UP
    vb = f"{x0:.2f} {y0:.2f} {x1 - x0:.2f} {y1 - y0:.2f}"
    red = "#{:02X}{:02X}{:02X}".format(*disc)

    lines = [
        "// Generated by scripts/trace-logo.py from assets-src/logo.jpg. Do not edit by hand.",
        "",
        f"/** The red of the logo's disc, sampled from the file. */",
        f"export const LOGO_RED = '{red}'",
        "",
        f"export const LOGO_VIEWBOX = '{vb}'",
        f"export const LOGO_ASPECT = {(x1 - x0) / (y1 - y0):.4f}",
        "",
        "/** One path per letter, left to right: S A I N T  A S L A N. */",
        "export const LOGO_GLYPHS = [",
    ]
    lines += [f"  '{d}'," for _, d in glyphs]
    lines.append("]")
    OUT.write_text("\n".join(lines) + "\n")
    print(len(glyphs), "glyphs", vb, red)


if __name__ == "__main__":
    main()
